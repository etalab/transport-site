#! mix run
# Regenerates apps/transport/priv/transport_schemas.yml from https://schema.data.gouv.fr, downloads the latest version
# of each JSON Schema in priv/vendored_schemas and refreshes the files already there. Schemas referenced by a new
# version (`$ref`) aren't downloaded: the JSONSchema validator tests fail if one is missing.
#
#   mix run --no-start scripts/update_transport_schemas.exs

{:ok, _} = Application.ensure_all_started(:req)

priv = Path.join(__DIR__, "../apps/transport/priv")
vendored_dir = Path.join(priv, "vendored_schemas")
base_url = "https://schema.data.gouv.fr/schemas"
get! = fn url -> url |> Req.get!(decode_body: false) |> Map.fetch!(:body) end

catalog =
  "https://schema.data.gouv.fr/schemas.json"
  |> get!.()
  |> Jason.decode!()
  |> Map.fetch!("schemas")
  |> Enum.filter(&("transport.data.gouv.fr" in &1["labels"] and &1["schema_type"] != "datapackage"))
  |> Map.new(fn %{"name" => name, "versions" => versions} = schema ->
    schema_file = versions |> List.last() |> Map.fetch!("schema_url") |> Path.basename()

    for %{"version_name" => version, "schema_url" => url} <- versions,
        url != "#{base_url}/#{name}/#{version}/#{schema_file}",
        do: raise("#{url} isn't the URL Transport.Schemas would build")

    {name,
     schema
     |> Map.take(["title", "schema_type"])
     |> Map.merge(%{"schema_file" => schema_file, "versions" => Enum.map(versions, & &1["version_name"])})}
  end)

header = """
# Schemas from https://schema.data.gouv.fr with the "transport.data.gouv.fr" label, datapackages excepted.
# Versions go from oldest to latest. A version's schema file is at
# https://schema.data.gouv.fr/schemas/<name>/<version>/<schema_file>
# For JSON Schemas, that file is also vendored for the latest version, see `priv/vendored_schemas`.
# Generated by `mix run --no-start scripts/update_transport_schemas.exs`.
"""

entries =
  catalog
  |> Enum.sort()
  |> Enum.map_join("\n", fn {name, schema} ->
    """
    #{name}:
      title: #{schema["title"]}
      schema_type: #{schema["schema_type"]}
      schema_file: #{schema["schema_file"]}
      versions: [#{Enum.map_join(schema["versions"], ", ", &~s("#{&1}"))}]
    """
  end)

yaml = header <> "\n" <> entries
if YamlElixir.read_from_string!(yaml) != catalog, do: raise("The generated YAML doesn't read back as the catalog")
File.write!(Path.join(priv, "transport_schemas.yml"), yaml)

latest_jsonschemas =
  for {name, %{"schema_type" => "jsonschema"} = schema} <- catalog,
      do: "#{base_url}/#{name}/#{List.last(schema["versions"])}/#{schema["schema_file"]}"

vendored =
  for path <- Path.wildcard("#{vendored_dir}/**/*.json"), do: "https://" <> Path.relative_to(path, vendored_dir)

for url <- Enum.uniq(latest_jsonschemas ++ vendored) do
  path = Path.join(vendored_dir, String.replace_prefix(url, "https://", ""))
  File.mkdir_p!(Path.dirname(path))
  File.write!(path, get!.(url))
end
